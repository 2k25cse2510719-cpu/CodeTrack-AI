"""Train supervised models only from defensibly labeled examples."""
import argparse
from pathlib import Path
import joblib
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline

TARGETS = ["interview_ready_label", "competition_ready_label"]
FEATURES = ["total_problems", "solved_count", "solve_rate", "easy_solved",
            "medium_solved", "hard_solved", "topic_count", "pattern_count",
            "solved_last_7_days", "solved_last_30_days", "platform_count",
            "revision_total", "revision_completed", "revision_completion_rate"]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True, help="CSV with features and real 0/1 target labels")
    parser.add_argument("--output-dir", default="CodeTrack-ML/models")
    args = parser.parse_args()
    data = pd.read_csv(args.data)
    missing = [c for c in FEATURES + TARGETS if c not in data.columns]
    if missing:
        raise SystemExit("Refusing to train; missing columns: " + ", ".join(missing) +
                         ". Use defensible real labels, never labels generated by the baseline.")
    for target in TARGETS:
        data[target] = pd.to_numeric(data[target], errors="coerce")
        if data[target].isna().any() or not set(data[target].unique()).issubset({0, 1}):
            raise SystemExit(f"Refusing to train: {target} must contain only 0/1 labels.")
        if data[target].value_counts().min() < 5:
            raise SystemExit(f"Refusing to train: {target} needs at least 5 rows in each class.")
    X = data[FEATURES].apply(pd.to_numeric, errors="coerce")
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    for target in TARGETS:
        y = data[target].astype(int)
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=0.25, random_state=42, stratify=y)
        model = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("classifier", RandomForestClassifier(n_estimators=200, random_state=42, class_weight="balanced"))
        ])
        model.fit(X_train, y_train)
        predictions = model.predict(X_test)
        print(f"\nTarget: {target}")
        print(f"Holdout accuracy: {accuracy_score(y_test, predictions):.3f}")
        print(classification_report(y_test, predictions, zero_division=0))
        joblib.dump({"model": model, "features": FEATURES, "target": target}, output / f"{target}.joblib")

if __name__ == "__main__":
    main()
